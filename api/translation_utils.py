"""
Утилиты для работы со значениями (переводами) слов БКРС.

Контекст: БКРС в исходном DSL имеет двухуровневую структуру:
  I прил./наречие          ← заголовок части речи
    1) hǎo хороший...      ← значение этой части речи
  II гл.                    ← следующая часть речи
    1) hào любить...

Наш парсер положил всё в плоский meanings. В результате при выборе
"первого значения" по position=1 для многозначных слов получаем
заголовок "I прил./наречие" или даже одиночную "I".

Этот модуль:
  1. is_section_header(text)         — определяет, является ли строка
                                       заголовком части речи
  2. clean_translation(text)         — убирает префиксы "1) hǎo " из значения
  3. get_meaningful_translations(...) — для пакета word_id возвращает
                                       первое осмысленное значение каждого

Логика выбора первого осмысленного значения вынесена сюда чтобы
переиспользовать одинаково в leveltest, progress и list сервисах.
"""
import re
from collections import defaultdict

from sqlalchemy import select
from sqlalchemy.orm import Session

from api.models import Meaning


# ============================================================================
# Определение заголовков частей речи
# ============================================================================

# Регулярка: строка начинается с римской цифры (I..X), за которой следует
# граница слова (\b — переход от \w к \W или конец строки).
#
# Это корректно отличает:
#   "I"                  → match (граница слова в конце)         → заголовок
#   "I прил./наречие"    → match (граница слова перед пробелом)  → заголовок
#   "II гл."             → match                                  → заголовок
#   "Италия"             → no match (I+т — оба \w, нет границы)  → НЕ заголовок
#   "1) hǎo хороший"     → no match (начинается с цифры)         → НЕ заголовок
#   "хороший"            → no match                              → НЕ заголовок
_SECTION_HEADER_RE = re.compile(r"^[IVX]+\b")


def is_section_header(text: str | None) -> bool:
    """
    True если строка похожа на заголовок части речи
    (начинается с римской цифры I..X с границей слова).
    """
    if not text:
        return True
    return bool(_SECTION_HEADER_RE.match(text.strip()))


# ============================================================================
# Очистка префиксов значений
# ============================================================================

# Регулярка для очистки префикса "1) hǎo " в начале перевода:
#   "1)" — номер значения с закрывающей скобкой
#   "\s*" — пробелы
#   "(?:[латиница-с-диакритикой]+\s+)*" — пиньинь (может быть несколько слогов)
_VALUE_PREFIX_RE = re.compile(
    r"^\d+\)\s*"
    r"(?:[a-zA-Z\u00C0-\u017F\u0100-\u024F\u2C60-\u2C7F]+\s+)*"
)


def clean_translation(text: str | None) -> str:
    """
    Очищает строку перевода от служебных префиксов БКРС.

    Примеры:
      "1) hǎo хороший; приятный"   → "хороший; приятный"
      "2) hào дружить, состоять"   → "дружить, состоять"
      "учиться; заниматься"        → "учиться; заниматься" (без изменений)
    """
    if not text:
        return ""
    return _VALUE_PREFIX_RE.sub("", text).strip()


# ============================================================================
# Пакетный поиск первых осмысленных значений
# ============================================================================

def get_meaningful_translations(
    dict_db: Session, word_ids: list[int], max_len: int = 80,
) -> dict[int, str]:
    """
    Для списка word_id возвращает {word_id: первое_осмысленное_значение}.

    Алгоритм:
      1. Одним SQL-запросом загружаем все meanings для указанных слов
      2. Группируем по word_id, сортируя по position
      3. Для каждого слова находим первое значение, которое:
         - не является заголовком части речи (is_section_header → False)
         - после clean_translation остаётся непустым
         - не длиннее max_len символов (отсекаем "простыни" неудобные для UI)

    Если ни одно значение слова не удовлетворяет критериям —
    word_id просто отсутствует в результате (вызывающий код должен это учесть).

    Это самый надёжный способ — фильтруем в Python после загрузки.
    SQL-фильтрация через GLOB ненадёжна для крайних случаев (одиночные "I" и т.п.).
    """
    if not word_ids:
        return {}

    rows = dict_db.execute(
        select(Meaning.word_id, Meaning.position, Meaning.translation)
        .where(Meaning.word_id.in_(word_ids))
        .order_by(Meaning.word_id, Meaning.position)
    ).all()

    # Группируем meanings по word_id (порядок уже отсортирован SQL'ем)
    by_word: dict[int, list[str]] = defaultdict(list)
    for wid, _pos, tr in rows:
        if tr:
            by_word[wid].append(tr)

    # Для каждого слова находим первое осмысленное значение
    result: dict[int, str] = {}
    for wid, translations in by_word.items():
        for tr in translations:
            if is_section_header(tr):
                continue
            cleaned = clean_translation(tr)
            if not cleaned or len(cleaned) > max_len:
                continue
            result[wid] = cleaned
            break  # нашли первое осмысленное — переходим к следующему слову

    return result
