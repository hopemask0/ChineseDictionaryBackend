-- ============================================================================
-- СХЕМА БАЗЫ ДАННЫХ СЛОВАРЯ БКРС
-- ============================================================================
-- Гибридный подход: нормализованные таблицы для целостности данных + 
-- виртуальная таблица FTS5 для быстрого полнотекстового поиска.
--
-- Принципы проектирования:
--   1. Нормализация до 3НФ для основных сущностей.
--   2. Денормализация только там, где это критично для производительности
--      поиска (FTS5).
--   3. Все таблицы поддерживают каскадное удаление через FOREIGN KEY 
--      (ON DELETE CASCADE), чтобы при удалении слова автоматически 
--      очищались связанные значения, примеры, пометы.
-- ============================================================================

-- Включаем поддержку внешних ключей (в SQLite по умолчанию выключена!)
PRAGMA foreign_keys = ON;

-- ============================================================================
-- Таблица 1: WORDS (Слова)
-- ============================================================================
-- Основная таблица. Каждая строка — одна словарная статья (одно китайское слово).
-- ============================================================================
CREATE TABLE IF NOT EXISTS words (
    id              INTEGER PRIMARY KEY AUTOINCREMENT,
    -- Иероглифическое написание слова (1-10 иероглифов обычно).
    -- UNIQUE: одно и то же слово не должно дублироваться в БД.
    headword        TEXT    NOT NULL UNIQUE,
    
    -- Транскрипция пиньинь с тонами: "nǐ hǎo", "xué xí".
    -- NULL допустим: ~1% статей в БКРС не имеют пиньинь (имена, термины).
    pinyin          TEXT,
    
    -- Пиньинь без тонов и пробелов: "nihao", "xuexi".
    -- Заполняется автоматически при вставке. Нужен для поиска "по пиньинь
    -- без тонов" — пользователю удобнее набрать "nihao", чем "nǐ hǎo".
    pinyin_plain    TEXT,
    
    -- Уровень HSK (1-6) или NULL, если слово не входит в стандартный словарь HSK.
    -- Заполняется отдельным скриптом из официальных списков HSK.
    hsk_level       INTEGER CHECK(hsk_level BETWEEN 1 AND 6),
    
    -- Категория слова — производная от помет.
    -- 'common'      — обычная лексика (по умолчанию)
    -- 'proper_noun' — имена собственные (фамилии, географические названия)
    -- 'term'        — узкоспециализированный термин (бот., мед., хим. и т.д.)
    -- 'rare'        — редкая лексика (игровые термины, локализации)
    -- Используется для фильтрации поиска: "искать только в обычной лексике".
    category        TEXT    NOT NULL DEFAULT 'common'
                    CHECK(category IN ('common', 'proper_noun', 'term', 'rare')),
    
    -- Длина слова в иероглифах. Производное поле для оптимизации запросов:
    -- "найти все односложные слова" работает быстрее с индексом, чем с 
    -- вычислением length(headword) каждый раз.
    char_length     INTEGER NOT NULL,
    
    -- Метаданные для отладки и аудита.
    created_at      DATETIME DEFAULT CURRENT_TIMESTAMP
);

-- Индексы для быстрого поиска
-- (на FTS-поиск работает отдельная таблица, эти — для точных запросов)
CREATE INDEX IF NOT EXISTS idx_words_headword     ON words(headword);
CREATE INDEX IF NOT EXISTS idx_words_pinyin_plain ON words(pinyin_plain);
CREATE INDEX IF NOT EXISTS idx_words_hsk          ON words(hsk_level) 
    WHERE hsk_level IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_words_category     ON words(category);

-- ============================================================================
-- Таблица 2: MEANINGS (Значения)
-- ============================================================================
-- Одно слово может иметь несколько значений. Каждое значение — отдельная 
-- строка с отдельным переводом и набором примеров.
-- 
-- Пример: слово 巨港 имеет 2 значения:
--   1) "очень крупный порт"
--   2) "Палембанг (город в Индонезии)"
-- ============================================================================
CREATE TABLE IF NOT EXISTS meanings (
    id              INTEGER PRIMARY KEY AUTOINCREMENT,
    word_id         INTEGER NOT NULL,
    
    -- Порядковый номер значения внутри слова (1, 2, 3, ...).
    -- Важен для отображения в правильном порядке.
    position        INTEGER NOT NULL,
    
    -- Уровень вложенности из исходного DSL ([m1]=1, [m2]=2, [m3]=3).
    -- Сохраняем для возможности отобразить иерархию значений.
    level           INTEGER NOT NULL DEFAULT 1,
    
    -- Текст перевода (без DSL-тегов).
    translation     TEXT    NOT NULL,
    
    FOREIGN KEY (word_id) REFERENCES words(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_meanings_word_id ON meanings(word_id);

-- ============================================================================
-- Таблица 3: EXAMPLES (Примеры использования)
-- ============================================================================
-- Примеры в БКРС привязаны к конкретному значению слова, а не к слову целиком.
-- Это важная деталь: один и тот же иероглиф в разных значениях иллюстрируется
-- разными примерами.
-- ============================================================================
CREATE TABLE IF NOT EXISTS examples (
    id              INTEGER PRIMARY KEY AUTOINCREMENT,
    meaning_id      INTEGER NOT NULL,
    
    chinese         TEXT    NOT NULL,  -- китайская часть примера
    russian         TEXT,               -- русский перевод (бывает пустым)
    
    FOREIGN KEY (meaning_id) REFERENCES meanings(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_examples_meaning_id ON examples(meaning_id);

-- ============================================================================
-- Таблица 4: LABELS (Пометы)
-- ============================================================================
-- Пометы из DSL: "бот.", "мед.", "ист.", "разг.", "сущ.", "гл." и т.д.
-- Хранятся отдельной таблицей со связью M:N, потому что:
--   - одно слово может иметь несколько помет
--   - одна помета может встречаться у тысяч слов
--   - удобно делать запрос "найти все слова с пометой 'бот.'"
-- ============================================================================
CREATE TABLE IF NOT EXISTS labels (
    id              INTEGER PRIMARY KEY AUTOINCREMENT,
    name            TEXT    NOT NULL UNIQUE   -- "бот.", "мед.", и т.д.
);

CREATE TABLE IF NOT EXISTS word_labels (
    word_id         INTEGER NOT NULL,
    label_id        INTEGER NOT NULL,
    PRIMARY KEY (word_id, label_id),
    FOREIGN KEY (word_id)  REFERENCES words(id)  ON DELETE CASCADE,
    FOREIGN KEY (label_id) REFERENCES labels(id) ON DELETE CASCADE
);

-- ============================================================================
-- Таблица 5: WORD_REFERENCES (Ссылки между словами)
-- ============================================================================
-- В DSL встречается тег [ref]другое_слово[/ref] — это означает "см. также".
-- Например, в статье 上海市 есть ссылка на 上海.
-- Реализуем как self-referencing M:N.
-- ============================================================================
CREATE TABLE IF NOT EXISTS word_references (
    from_word_id    INTEGER NOT NULL,
    to_headword     TEXT    NOT NULL,  -- хранится строкой, т.к. целевое слово 
                                        -- может ещё не быть в базе при загрузке
    PRIMARY KEY (from_word_id, to_headword),
    FOREIGN KEY (from_word_id) REFERENCES words(id) ON DELETE CASCADE
);

-- ============================================================================
-- Таблица 6: WORDS_FTS (Полнотекстовый поиск)
-- ============================================================================
-- Виртуальная таблица FTS5 — это специальный механизм SQLite для быстрого
-- полнотекстового поиска. Под капотом строит инвертированный индекс по 
-- словам и поддерживает запросы вида MATCH 'термин'.
--
-- Токенизатор unicode61 правильно работает с китайскими иероглифами, 
-- кириллицей и латиницей одновременно.
--
-- Включаем remove_diacritics=2 — это значит, что при поиске "ni hao" 
-- найдётся слово с пиньинь "nǐ hǎo" (диакритика игнорируется).
-- ============================================================================
CREATE VIRTUAL TABLE IF NOT EXISTS words_fts USING fts5(
    headword,           -- иероглиф
    pinyin,             -- пиньинь с тонами
    pinyin_plain,       -- пиньинь без тонов (для удобного ввода)
    translations,       -- объединённые переводы всех значений (для рус. поиска)
    
    -- content='words' нельзя — нужен JOIN с meanings, поэтому 'contentless'
    tokenize = 'unicode61 remove_diacritics 2'
);

-- ============================================================================
-- Таблица 7: META (Метаданные базы)
-- ============================================================================
-- Хранит технические метаданные: версия словаря, дата сборки и т.д.
-- На защите можно сослаться: "БД содержит версионирование для отслеживания 
-- обновлений словаря".
-- ============================================================================
CREATE TABLE IF NOT EXISTS meta (
    key             TEXT PRIMARY KEY,
    value           TEXT
);

